export function getLaboratoryById(id: string): LaboratoryItem | undefined {
  return LABORATORY_REGISTRY.find((item) => item.id === id);
}

export function getLaboratoriesByCategory(categoryId: string): LaboratoryItem[] {
  if (categoryId === 'all') {
    return LABORATORY_REGISTRY;
  }
  return LABORATORY_REGISTRY.filter((item) => item.categoryId === categoryId);
}

export function searchLaboratories(query: string, categoryId = 'all'): LaboratoryItem[] {
  const baseList = getLaboratoriesByCategory(categoryId);
  const q = query.trim().toLowerCase();
  if (!q) return baseList;

  return baseList.filter((item) => {
    if (item.title.toLowerCase().includes(q)) return true;
    if (item.shortTitle.toLowerCase().includes(q)) return true;
    if (item.description.toLowerCase().includes(q)) return true;
    if (item.categoryName.toLowerCase().includes(q)) return true;
    if (item.chapterId && item.chapterId.includes(q)) return true;
    if (item.chapterId && `bab ${item.chapterId}`.includes(q)) return true;
    if (item.chapterId && `chapter ${item.chapterId}`.includes(q)) return true;
    if (item.keywords.some((k) => k.toLowerCase().includes(q))) return true;
    return false;
  });
}

